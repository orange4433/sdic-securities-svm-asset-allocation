def load_futures_nav(file_path):
    """Load the CSI 500 futures NAV series."""
    print(f"🔍 正在读取中证500股指期货净值曲线: {file_path}")
    try:
        df = pd.read_csv(file_path, parse_dates=['trade_date'])
        df.set_index('trade_date', inplace=True)
        df.index = pd.to_datetime(df.index)
        
        # Validate the NAV data.
        if 'nav' not in df.columns:
            print("❌ 错误：找不到 'nav' 列！")
            return None
        
        # Filter observations after the start date.
        df = df[df.index >= START_DATE]
        
        print(f"✅ 成功加载中证500股指期货净值曲线，数据点: {len(df)}")
        return df[['nav']]  # Keep only NAV.
    except Exception as e:
        print(f"❌ 读取中证500股指期货净值曲线失败: {e}")
        return None

