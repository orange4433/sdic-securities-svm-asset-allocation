# 3. Calculate metrics.
# ----------------------------
def calculate_metrics(df, name):
    """Calculate performance metrics."""
    if len(df) == 0:
        print(f"⚠️ {name} 数据为空，无法计算指标")
        return None, None
    
    if 'close' in df.columns:
        # Calculate returns from prices.
        df['return'] = df['close'].pct_change(fill_method=None)
    elif 'nav' in df.columns:
        # Calculate returns from NAV.
        df['return'] = df['nav'].pct_change(fill_method=None)
    else:
        print(f"❌ {name} 数据中既无 'close' 也无 'nav' 列")
        return None, None
    
    # Drop missing returns.
    df = df.dropna(subset=['return'])
    
    if len(df) == 0:
        print(f"⚠️ {name} 收益率计算后数据为空")
        return None, None
    
    # Calculate annualized return.
    total_days = (df.index[-1] - df.index[0]).days
    if total_days > 0:
        cumulative_return = df['return'].add(1).prod() - 1
        annualized_return = (1 + cumulative_return) ** (365.25 / total_days) - 1
    else:
        annualized_return = np.nan
    
    # Calculate annualized volatility.
    annualized_volatility = df['return'].std() * np.sqrt(252)
    
    # Calculate the Sharpe ratio with a zero risk-free rate.
    sharpe_ratio = annualized_return / annualized_volatility if annualized_volatility != 0 else np.nan
    
    # Calculate maximum drawdown.
    if 'nav' in df.columns:
        cum_return = (1 + df['return']).cumprod()
        cum_max = cum_return.cummax()
        drawdown = (cum_max - cum_return) / cum_max
        max_drawdown = drawdown.max()
    elif 'close' in df.columns:
        cum_return = (df['close'] / df['close'].iloc[0])
        cum_max = cum_return.cummax()
        drawdown = (cum_max - cum_return) / cum_max
        max_drawdown = drawdown.max()
    else:
        max_drawdown = np.nan
    
    # Save the calculated metrics.
    metrics = {
        'annual_return': annualized_return,
        'annual_volatility': annualized_volatility,
        'sharpe_ratio': sharpe_ratio,
        'max_drawdown': max_drawdown,
        'cumulative_return': cumulative_return
    }
    
    return metrics, df

