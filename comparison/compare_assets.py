def read_index_data(file_path, date_col_name='交易日期', close_col_name='收盘价'):
    """Read and process index data."""
    print(f"🔍 正在读取文件: {file_path}")
    
    try:
        # Select the reader by file extension.
        if file_path.endswith('.csv'):
            df = pd.read_csv(file_path)
        elif file_path.endswith('.xlsx'):
            df = pd.read_excel(file_path)
        else:
            print(f"❌ 不支持的文件格式: {file_path}")
            return None
    except Exception as e:
        print(f"❌ 文件读取失败: {e}")
        return None

    # Detect date and price columns.
    date_col_candidates = ['date', '日期', '交易日期', 'trade_date', '时间', 'timestamp']
    close_col_candidates = ['close', '收盘价', 'nav', '净值', 'price', 'value']
    
    date_col = None
    for col in date_col_candidates:
        if col in df.columns:
            date_col = col
            break
    
    close_col = None
    for col in close_col_candidates:
        if col in df.columns:
            close_col = col
            break
    
    if not date_col:
        print(f"❌ 错误：找不到日期列！文件列名为：{list(df.columns)}")
        return None
    if not close_col:
        print(f"❌ 错误：找不到价格列！文件列名为：{list(df.columns)}")
        return None

    print(f"📄 数据形状: {df.shape}")
    print(f"📊 前几行数据:\n{df[[date_col, close_col]].head()}")

    df_selected = df[[date_col, close_col]].copy()
    df_selected.columns = ['date', 'close']

    # Normalize numeric formatting.
    df_selected['close'] = (
        df_selected['close']
        .astype(str)
        .str.replace(',', '', regex=False)
        .replace('nan', np.nan)
    )
    df_selected['close'] = pd.to_numeric(df_selected['close'], errors='coerce')

    # Convert dates.
    df_selected['date'] = pd.to_datetime(df_selected['date'], errors='coerce')

    # Remove invalid rows.
    before_drop = len(df_selected)
    df_selected.dropna(inplace=True)
    after_drop = len(df_selected)
    print(f"🧹 数据清洗：{before_drop} → {after_drop} 行（删除 NaN）")

    if len(df_selected) == 0:
        print("❌ 清洗后数据为空！请检查数据")
        return None

    df_selected = df_selected.sort_values('date').reset_index(drop=True)
    df_selected.set_index('date', inplace=True)

    # Filter observations after the start date.
    df_selected = df_selected[df_selected.index >= START_DATE]
    
    print(f"✅ {file_path} 处理完成，共 {len(df_selected)} 个有效交易日")
    return df_selected

