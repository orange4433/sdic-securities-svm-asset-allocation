# 6. Plot four annual metrics separately for five assets, including Sharpe ratios.
# ----------------------------
def plot_yearly_metrics(all_data):
    """Compare asset risk and return metrics separately for each year."""
    # Prepare annual data.
    yearly_metrics = {}
    
    for name, data in all_data.items():
        df = data["df"].copy()
        metrics = {}
        
        # Add a year column.
        df['year'] = df.index.year
        
        # Calculate metrics by year.
        for year, group in df.groupby('year'):
            if len(group) < 20:  # Require at least 20 trading days.
                continue
                
            # Calculate the annual return.
            if 'nav' in group.columns:
                annual_return = (group['nav'].iloc[-1] / group['nav'].iloc[0]) - 1
            elif 'close' in group.columns:
                annual_return = (group['close'].iloc[-1] / group['close'].iloc[0]) - 1
            else:
                continue
                
            # Calculate annualized volatility.
            if 'return' in group.columns:
                annual_volatility = group['return'].std() * np.sqrt(252)
            else:
                continue
                
            # Calculate the Sharpe ratio with a zero risk-free rate.
            sharpe_ratio = annual_return / annual_volatility if annual_volatility != 0 else np.nan
                
            # Calculate maximum drawdown.
            if 'nav' in group.columns:
                cum_return = group['nav'] / group['nav'].iloc[0]
                cum_max = cum_return.cummax()
                drawdown = (cum_max - cum_return) / cum_max
                max_drawdown = drawdown.max()
            elif 'close' in group.columns:
                cum_return = group['close'] / group['close'].iloc[0]
                cum_max = cum_return.cummax()
                drawdown = (cum_max - cum_return) / cum_max
                max_drawdown = drawdown.max()
            else:
                max_drawdown = np.nan
                
            # Save annual metrics.
            metrics[year] = {
                'annual_return': annual_return,
                'annual_volatility': annual_volatility,
                'sharpe_ratio': sharpe_ratio,
                'max_drawdown': max_drawdown
            }
        
        yearly_metrics[name] = metrics
    
    # Identify all years.
    all_years = set()
    for metrics in yearly_metrics.values():
        all_years.update(metrics.keys())
    all_years = sorted(all_years)
    
    # Create separate charts for four metrics.
    fig, axes = plt.subplots(4, 1, figsize=(14, 28))
    fig.suptitle('各资产分年度风险收益指标对比（每年分开显示）', fontsize=16, fontweight='bold')
    
    # Five distinct colors
    colors = ['#1f77b4', '#2ca02c', '#d62728', '#9467bd', '#8c564b']
    assets = list(yearly_metrics.keys())
    
    # Set bar widths and positions.
    bar_width = 0.15
    positions = np.arange(len(all_years))
    
    # 1. Plot annualized returns.
    ax1 = axes[0]
    for i, (name, metrics) in enumerate(yearly_metrics.items()):
        returns = [metrics.get(year, {}).get('annual_return', 0) * 100 for year in all_years]
        ax1.bar(positions + i * bar_width, returns, width=bar_width, 
                label=name, color=colors[i], alpha=0.8)
    
    ax1.set_title('年化收益率 (%)', fontsize=14)
    ax1.set_ylabel('收益率 (%)', fontsize=12)
    ax1.set_xticks(positions + bar_width * (len(assets) - 1) / 2)
    ax1.set_xticklabels(all_years, fontsize=10)
    ax1.legend(fontsize=10)
    ax1.grid(True, axis='y', linestyle='--', alpha=0.3)
    
    # 2. Plot annualized volatility.
    ax2 = axes[1]
    for i, (name, metrics) in enumerate(yearly_metrics.items()):
        volatilities = [metrics.get(year, {}).get('annual_volatility', 0) * 100 for year in all_years]
        ax2.bar(positions + i * bar_width, volatilities, width=bar_width, 
                label=name, color=colors[i], alpha=0.8)
    
    ax2.set_title('年化波动率 (%)', fontsize=14)
    ax2.set_ylabel('波动率 (%)', fontsize=12)
    ax2.set_xticks(positions + bar_width * (len(assets) - 1) / 2)
    ax2.set_xticklabels(all_years, fontsize=10)
    ax2.grid(True, axis='y', linestyle='--', alpha=0.3)
    
    # 3. Plot Sharpe ratios.
    ax3 = axes[2]
    for i, (name, metrics) in enumerate(yearly_metrics.items()):
        sharpe_ratios = [metrics.get(year, {}).get('sharpe_ratio', 0) for year in all_years]
        ax3.bar(positions + i * bar_width, sharpe_ratios, width=bar_width, 
                label=name, color=colors[i], alpha=0.8)
    
    ax3.set_title('夏普比率', fontsize=14)
    ax3.set_ylabel('夏普比率', fontsize=12)
    ax3.set_xticks(positions + bar_width * (len(assets) - 1) / 2)
    ax3.set_xticklabels(all_years, fontsize=10)
    ax3.grid(True, axis='y', linestyle='--', alpha=0.3)
    
    # 4. Plot maximum drawdown.
    ax4 = axes[3]
    for i, (name, metrics) in enumerate(yearly_metrics.items()):
        drawdowns = [metrics.get(year, {}).get('max_drawdown', 0) * 100 for year in all_years]
        ax4.bar(positions + i * bar_width, drawdowns, width=bar_width, 
                label=name, color=colors[i], alpha=0.8)
    
    ax4.set_title('最大回撤 (%)', fontsize=14)
    ax4.set_xlabel('年份', fontsize=12)
    ax4.set_ylabel('回撤 (%)', fontsize=12)
    ax4.set_xticks(positions + bar_width * (len(assets) - 1) / 2)
    ax4.set_xticklabels(all_years, fontsize=10)
    ax4.grid(True, axis='y', linestyle='--', alpha=0.3)
    
    # Add data labels.
    for ax in axes:
        for container in ax.containers:
            if ax == ax3:  # Sharpe ratios are not percentages.
                ax.bar_label(container, fmt='%.2f', fontsize=6, padding=2)  # Reduce font size to fit more data.
            else:
                ax.bar_label(container, fmt='%.1f%%', fontsize=6, padding=2)  # Reduce font size to fit more data.
    
    plt.tight_layout(rect=[0, 0, 1, 0.96])  # Leave space for the title.
    plt.savefig('年度指标对比_每年分开.png', dpi=300, bbox_inches='tight')
    print("✅ 年度指标图已保存: 年度指标对比_每年分开.png")
    plt.show()

