def plot_nav_curves(all_data):
    """Plot NAV curves for all assets."""
    plt.figure(figsize=(16, 8))
    
    # Five distinct colors
    colors = ['#1f77b4', '#2ca02c', '#d62728', '#9467bd', '#8c564b']
    
    # Plot each asset's NAV curve.
    for i, (name, data) in enumerate(all_data.items()):
        df = data["df"]
        
        # Calculate normalized NAV.
        if 'nav' in df.columns:
            # For futures NAV data
            normalized_nav = df['nav'] / df['nav'].iloc[0]
        elif 'close' in df.columns:
            # For price data
            normalized_nav = df['close'] / df['close'].iloc[0]
        else:
            continue
        
        # Draw the curve.
        plt.plot(df.index, normalized_nav, label=name, color=colors[i], linewidth=2)
    
    # Set chart properties.
    plt.title('五大资产净值走势对比 (2018-2025)', fontsize=16, fontweight='bold')
    plt.xlabel('日期', fontsize=12)
    plt.ylabel('净值 (归一化至1)', fontsize=12)
    plt.legend(fontsize=12, loc='upper left')
    plt.grid(True, linestyle='--', alpha=0.3)
    
    # Format dates.
    plt.gca().xaxis.set_major_locator(mdates.YearLocator())
    plt.gca().xaxis.set_major_formatter(mdates.DateFormatter('%Y'))
    plt.xticks(rotation=45)
    
    plt.tight_layout()
    plt.savefig('五大资产净值走势对比.png', dpi=300)
    print("✅ 净值曲线图已保存: 五大资产净值走势对比.png")
    plt.show()

